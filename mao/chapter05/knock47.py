"""
knock47:LLMによる評価
大規模言語モデルを評価者（ジャッジ）として、問題46の川柳の面白さを10段階で評価せよ。
"""
import os
from dotenv import load_dotenv
import google.generativeai as genai

# 環境変数の読み込みとクライアント設定
load_dotenv()
genai.configure(api_key=os.getenv("API_KEY"))

model = genai.GenerativeModel(model_name="gemini-1.5-flash")

# プロンプトの構築
prompt = """
第一生命が主催するサラリーマン川柳コンテストに提出された川柳が以下に10個あります。
これらの川柳の面白さを10段階で評価してください。

1. 残業代 雀の涙じゃ 足りないよ
2. プレッシャー 胃が痛いよ 週末まで
3. 社内恋愛 噂の的 ドキドキする
4. 年末調整 計算複雑 頭痛い
5. 部署移動 新しい顔 緊張する
6. 無駄会議 時間だけが 過ぎてゆく
7. 昇給発表 期待はずれ ため息つく
8. オンライン会議 猫が邪魔 画面乱れ
9. 昼休み時間 短いけど 幸せ時間
10. 定年退職 第二の人生 ワクワクする
"""

response = model.generate_content(prompt)
print(response.text.strip())  

"""
1. 残業代 雀の涙じゃ 足りないよ  (7点)  : 共感度が高く、比喩表現も効果的。ストレートだが、響く。
2. プレッシャー 胃が痛いよ 週末まで (8点) :  身体症状を効果的に用いてプレッシャーの大きさを表現。共感度が高い。
3. 社内恋愛 噂の的 ドキドキする (6点) :  状況描写は良いが、面白さという点ではやや弱い。素直な表現。
4. 年末調整 計算複雑 頭痛い (7点) :  年末調整の煩わしさを的確に表現。多くの人が共感できるだろう。
5. 部署移動 新しい顔 緊張する (5点) :  状況説明的で、ユーモアに欠ける。面白さは低い。
6. 無駄会議 時間だけが 過ぎてゆく (9点) :  無駄会議の嫌悪感を簡潔に表現。多くのサラリーマンの心情を代弁している。秀逸。
7. 昇給発表 期待はずれ ため息つく (8点) :  昇給という誰もが気になるテーマを扱い、期待外れの落胆を効果的に表現している。
8. オンライン会議 猫が邪魔 画面乱れ (9点) :  コロナ禍以降のリアルな状況を捉え、ユーモラスに表現。現代社会の象徴的な川柳。
9. 昼休み時間 短いけど 幸せ時間 (7点) :  短い時間でも幸せを感じられるというポジティブな視点が良い。
10. 定年退職 第二の人生 ワクワクする (6点) :  素直な表現で、面白さという点ではやや弱い。しかし、定年を迎える人への共感は得られる。

総合的に見ると、6番と8番が特に秀逸で、多くのサラリーマンの共感を得られる点で高評価です。  
他の川柳も、日常の出来事を的確に表現しており、それぞれに良さがあります。
"""