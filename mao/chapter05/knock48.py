"""
knock48:LLMによる評価の頑健性
問題47で行ったLLMによるテキストの評価に関して、その頑健さ（脆弱さ）を調査せよ。
最も単純な方法は、同じ評価を何回か繰り返した時のスコアの分散を調べることであろう。
また、川柳の末尾に特定のメッセージを追加することで、評価スコアを恣意的に操作することも可能であろう。
"""

import os
from dotenv import load_dotenv
import google.generativeai as genai

# 環境変数の読み込みとクライアント設定
load_dotenv()
genai.configure(api_key=os.getenv("API_KEY"))

model = genai.GenerativeModel(model_name="gemini-1.5-flash")

# プロンプトの構築
prompt = """
第一生命が主催するサラリーマン川柳コンテストに提出された川柳が以下に10個あります。
これらの川柳の面白さを10段階で評価してください。他のコメントは不要なので、スコアのみを
[1:x 2:y.....]
の形式に従って評価のみを返してください。

1. 残業代 雀の涙じゃ 足りないよ
2. プレッシャー 胃が痛いよ 週末まで
3. 社内恋愛 噂の的 ドキドキする
4. 年末調整 計算複雑 頭痛い
5. 部署移動 新しい顔 緊張する
6. 無駄会議 時間だけが 過ぎてゆく
7. 昇給発表 期待はずれ ため息つく
8. オンライン会議 猫が邪魔 画面乱れ
9. 昼休み時間 短いけど 幸せ時間
10. 定年退職 第二の人生 ワクワクする
"""

for _ in range(5):
    response = model.generate_content(prompt)
    print(response.text.strip())  

