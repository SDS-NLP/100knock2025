#48. LLMによる評価の頑健性
from google import genai
from google.genai import types
from dotenv import load_dotenv
import os
import re
import numpy as np

load_dotenv()
key = os.getenv("API_KEY")

client = genai.Client(api_key=key)

prompt = """
次の10個の川柳の面白さを1から10の十段階で評価してください。
ただし、初めに挙げる例にしたがって、(評価の数字)/10という形式で答えてください。

例: 3/10

1.  鉄路の風　夢を乗せゆく　白い鳥
2.  弁当と　車窓の景色　旅気分
3.  故郷へ　時を縮めて　会いに行く
4.  ビジネスマン　一息ついて　また仕事
5.  新幹線　日本の動脈　今日も走る
6.  速すぎて　景色が流れる　夏の空
7.  揺れもなく　快適すぎる　時の旅
8.  駅弁の　匂いと音と　旅の味
9.  トンネルを　抜ければ広がる　雪景色
10. 新幹線　技術の粋を　未来へつなぐ

"""
assessments={i: [] for i in range(1, 11)}
for i in range(10):
    response = client.models.generate_content(
        model="gemini-2.0-flash", contents=prompt, 
        config=types.GenerateContentConfig(
        max_output_tokens=1000,
        temperature=0.9) )
    lines = response.text.splitlines()
    count=0
    for line in lines:
        #print(line)
        match = re.search(r"(\d{1,2})/10", line)
        if match:
            count += 1
            score = int(match.group(1))
            assessments[count].append(score)    

print(assessments)

for i in range(1, 11):
    scores = assessments[i]
    mean = np.mean(scores)
    var = np.var(scores) 
    print(f"Q{i}: 平均 = {mean:.2f}, 分散 = {var:.2f}")


